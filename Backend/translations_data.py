def get_translations_for_language(language: str = "English") -> dict:
    """
    Extracts a flattened key-value dictionary for the target language.
    language: 'English' | 'Tagalog' | 'Cebuano'
    """
    valid_langs = ["English", "Tagalog", "Cebuano"]
    lang = language.capitalize() if language else "English"
    if lang not in valid_langs:
        lang = "English"

    strings_map = {}
    for key, trans in UI_STRINGS.items():
        strings_map[key] = trans.get(lang, key)

    meals_map = {}
    for key, trans in MEAL_TITLES.items():
        meals_map[key] = trans.get(lang, key)

    cat_map = {}
    for key, trans in CATEGORIES.items():
        cat_map[key] = trans.get(lang, key)

    return {
        "language": lang,
        "version": "1.0",
        "strings": strings_map,
        "meal_titles": meals_map,
        "categories": cat_map
    }
